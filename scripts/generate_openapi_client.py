"""Generate typed TypeScript OpenAPI route & schema definitions from FastAPI app.openapi()."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from flowpilot_api.app import create_app
from flowpilot_api.config import Settings


def _ts_type_from_schema(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        ref_name = str(schema["$ref"]).split("/")[-1]
        return f"OpenApiComponents['{ref_name}']"
    if "anyOf" in schema:
        return " | ".join(_ts_type_from_schema(s) for s in schema["anyOf"])
    t = schema.get("type")
    if t == "string":
        if "enum" in schema:
            return " | ".join(json.dumps(v) for v in schema["enum"])
        return "string"
    if t in ("integer", "number"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array":
        item_t = _ts_type_from_schema(schema.get("items", {}))
        return f"Array<{item_t}>"
    if t == "object":
        return "Record<string, unknown>"
    return "unknown"


def generate_typescript_client(output_path: Path) -> int:
    """Export FastAPI OpenAPI paths & component schemas as strict TypeScript types."""
    app = create_app(Settings(database_url="sqlite+aiosqlite:///:memory:"))
    spec = app.openapi()
    paths = spec.get("paths", {})
    schemas = spec.get("components", {}).get("schemas", {})

    version_json = json.dumps(spec.get("info", {}).get("version", "0.1.0"))
    lines: list[str] = [
        "/* AUTO-GENERATED by scripts/generate_openapi_client.py from FastAPI OpenAPI schema. */",
        "/* Do not hand-edit; re-run `uv run python scripts/generate_openapi_client.py`. */",
        "",
        f"export const OPENAPI_VERSION = {version_json} as const;",
        "",
        "export const API_PATHS = {",
    ]
    for path_key in sorted(paths.keys()):
        methods = sorted(m.upper() for m in paths[path_key])
        lines.append(f"  {json.dumps(path_key)}: {json.dumps(methods)} as const,")
    lines.append("} as const;")
    lines.append("")
    lines.append("export type ApiPath = keyof typeof API_PATHS;")
    lines.append("")
    lines.append("export interface OpenApiComponents {")

    for name in sorted(schemas.keys()):
        schema = schemas[name]
        props = schema.get("properties", {})
        required = set(schema.get("required", []))
        if not props:
            lines.append(f"  {json.dumps(name)}: {_ts_type_from_schema(schema)};")
            continue
        lines.append(f"  {json.dumps(name)}: {{")
        for prop_name, prop_schema in props.items():
            opt = "" if prop_name in required else "?"
            lines.append(f"    {json.dumps(prop_name)}{opt}: {_ts_type_from_schema(prop_schema)};")
        lines.append("  };")

    lines.append("}")
    lines.append("")

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text("\n".join(lines), encoding="utf-8")
    return len(paths)


def main() -> None:
    root = Path(__file__).resolve().parents[1]
    target = root / "apps" / "web" / "src" / "lib" / "openapi.generated.ts"
    count = generate_typescript_client(target)
    print(f"Generated {target} with {count} OpenAPI paths.")


if __name__ == "__main__":
    main()
